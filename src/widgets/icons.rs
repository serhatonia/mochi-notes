/// Creates an icon as a text widget.
pub fn icon<'a>(glyph: Icon, size: f32, color: Color) -> Text<'a> {
    text(glyph.glyph().to_string())
        .font(theme::FONT_ICON)
        .size(size)
        .color(color)
}
